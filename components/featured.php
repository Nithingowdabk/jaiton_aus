          gsap.fromTo(panel, { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.4, ease: "power2.out" });
        } else { panel.style.opacity = 1; }
      }
    });
  });

  /* Counters */
  const countUp = () => {
    document.querySelectorAll(".cs-stat-num").forEach(el => {
      const t = parseInt(el.dataset.target); if (!t) return;
      const o = { v: 0 };
      if (typeof gsap !== "undefined") gsap.to(o, { v: t, duration: 1.5, ease: "power2.out", onUpdate: () => { el.innerText = Math.floor(o.v); } });
    });
  };
  if (typeof ScrollTrigger !== "undefined") ScrollTrigger.create({ trigger: ".featured-section", start: "top center", once: true, onEnter: countUp });
  else countUp();
});
