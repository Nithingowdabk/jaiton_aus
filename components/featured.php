<script>
document.addEventListener("DOMContentLoaded", () => {
  // Select navigation tabs and display blocks
  const tabBtns = document.querySelectorAll(".nav-tab-btn");
  const displayTabs = document.querySelectorAll(".project-display-tab");
  
  tabBtns.forEach((btn, index) => {
    btn.addEventListener("click", () => {
      // Clear active states from tabs and btn classes
      tabBtns.forEach(b => b.classList.remove("active"));
      displayTabs.forEach(t => t.classList.remove("active"));
      
      // Activate selected elements
      btn.classList.add("active");
      const targetTab = document.getElementById(`project-tab-${index}`);
      if (targetTab) {
        targetTab.classList.add("active");
        
        // Trigger quick reveal animation on active display block
        gsap.fromTo(targetTab, 
          { opacity: 0, y: 15 },
          { opacity: 1, y: 0, duration: 0.5, ease: "power2.out" }
        );
      }
    });
  });

  // Numeric count animations for statistics counters
  const statNumbers = document.querySelectorAll(".counter-num");
  const countStats = () => {
    statNumbers.forEach(num => {
      const target = parseInt(num.getAttribute("data-target"));
      const tempVal = { val: 0 };
      gsap.to(tempVal, {
        val: target,
        duration: 1.5,
        ease: "power2.out",
        onUpdate: () => {
          num.innerText = Math.floor(tempVal.val);
        }
      });
    });
  };

  // Trigger counters when scrolled into view
  if (typeof ScrollTrigger !== "undefined") {
    ScrollTrigger.create({
      trigger: ".featured-section",
      start: "top center",
      once: true,
      onEnter: countStats
    });
  } else {
    // Fallback if ScrollTrigger is not ready
    countStats();
  }

  // Magnetic button hover links
  const magneticButtons = document.querySelectorAll(".btn-magnetic");
  magneticButtons.forEach((btn) => {
    btn.addEventListener("mousemove", (e) => {
      const bounds = btn.getBoundingClientRect();
      const x = e.clientX - bounds.left - bounds.width / 2;
      const y = e.clientY - bounds.top - bounds.height / 2;
      
      gsap.to(btn, {
        x: x * 0.3,
        y: y * 0.3,
        duration: 0.3,
