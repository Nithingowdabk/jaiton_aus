document.addEventListener("DOMContentLoaded", () => {
  const section = document.getElementById("why-jaiton");

  // Intersection Observer to pause SVG animations off-screen
  if ("IntersectionObserver" in window && section) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) {
          document.body.classList.add("exec-animations-paused");
        } else {
          document.body.classList.remove("exec-animations-paused");
        }
      });
    }, { threshold: 0.1 });

    observer.observe(section);
  }
});
</script>

