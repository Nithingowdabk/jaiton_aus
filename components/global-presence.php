<script>
document.addEventListener("DOMContentLoaded", () => {
  const ribbonItems = document.querySelectorAll(".ribbon-item");
  const routePaths = document.querySelectorAll(".ops-route-path");

  ribbonItems.forEach(item => {
    item.addEventListener("mouseenter", () => {
      const targetRouteClass = item.getAttribute("data-route");
      routePaths.forEach(path => {
        if (path.classList.contains(targetRouteClass)) {
          path.classList.add("highlighted");
        } else {
          path.classList.add("dimmed");
        }
      });
    });

    item.addEventListener("mouseleave", () => {
      routePaths.forEach(path => {
        path.classList.remove("highlighted", "dimmed");
      });
    });
  });
});
</script>

