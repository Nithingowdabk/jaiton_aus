<script>
document.addEventListener("DOMContentLoaded", () => {
  // 1. Dynamic Local Clocks
  const updateClocks = () => {
    const now = new Date();
    const timeOpts = (timeZone) => ({
      timeZone,
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: true
    });

    const syd = document.getElementById("gclock-syd");
    const blr = document.getElementById("gclock-blr");
    const sgp = document.getElementById("gclock-sgp");
    const dxb = document.getElementById("gclock-dxb");
    const jnb = document.getElementById("gclock-jnb");

    if (syd) syd.textContent = now.toLocaleTimeString("en-AU", timeOpts("Australia/Sydney"));
    if (blr) blr.textContent = now.toLocaleTimeString("en-IN", timeOpts("Asia/Kolkata"));
    if (sgp) sgp.textContent = now.toLocaleTimeString("en-SG", timeOpts("Asia/Singapore"));
    if (dxb) dxb.textContent = now.toLocaleTimeString("en-AE", timeOpts("Asia/Dubai"));
    if (jnb) jnb.textContent = now.toLocaleTimeString("en-ZA", timeOpts("Africa/Johannesburg"));
  };

  updateClocks();
  setInterval(updateClocks, 1000);

  // 2. Pins Interaction
  const pins = document.querySelectorAll(".presence-pin");
  const regionPanels = document.querySelectorAll(".hub-region-panel");

  pins.forEach(pin => {
    const activatePin = () => {
      const hubKey = pin.getAttribute("data-hub");
      pins.forEach(p => p.classList.remove("active"));
      regionPanels.forEach(rp => rp.classList.remove("active"));

      pin.classList.add("active");
      const targetPanel = document.getElementById(`hub-${hubKey}`);
      if (targetPanel) {
        targetPanel.classList.add("active");
      }
    };

    pin.addEventListener("mouseenter", activatePin);
    pin.addEventListener("click", activatePin);
  });

  // 3. Rotating Activity Feed Ticker
  const activityItems = [
    "✓ Deployment completed",
    "✓ Cloud sync active",
    "✓ Sprint approved",
    "✓ QA completed",
    "✓ API health normal"
  ];
  let activityIdx = 0;
  const activityEl = document.getElementById("dash-activity-text");

  if (activityEl) {
    setInterval(() => {
      activityIdx = (activityIdx + 1) % activityItems.length;
      activityEl.style.opacity = 0;
      setTimeout(() => {
        activityEl.querySelector("span").textContent = activityItems[activityIdx];
        activityEl.style.opacity = 1;
      }, 250);
    }, 3500);
  }
});
</script>

